# ---------------- CREATE ATTENDANCE SESSION ----------------

@app.route("/create-session", methods=["GET", "POST"])
def create_session():

    message = ""
    qr_image = None
    session_id = None

    if request.method == "POST":

        session_name = request.form.get(
            "session_name", ""
        ).strip()

        if not session_name:

            message = "Please enter a session name."

        else:

            session_date = datetime.now(
                ZoneInfo("Asia/Kolkata")
            ).date().isoformat()

            connection = get_database_connection()

            try:

                cursor = connection.cursor()

                cursor.execute("""
                    INSERT INTO sessions
                    (session_name, session_date)
                    VALUES (%s, %s)
                    RETURNING id
                """, (session_name, session_date))

                session_id = cursor.fetchone()["id"]

                connection.commit()

            except Exception:

                connection.rollback()
                raise

            finally:

                connection.close()

            # Create QR-code image

            qr_folder = os.path.join(
                app.static_folder,
                "qrcodes"
            )

            os.makedirs(qr_folder, exist_ok=True)

            # Automatically use the current website address

            session_url = (
                f"{request.host_url.rstrip('/')}"
                f"/mark-attendance/{session_id}"
            )

            qr = qrcode.make(session_url)

            qr_filename = f"session_{session_id}.png"

            qr_path = os.path.join(
                qr_folder,
                qr_filename
            )

            qr.save(qr_path)

            qr_image = f"qrcodes/{qr_filename}"

            message = "Attendance session created successfully!"

    return render_template(
        "create_session.html",
        message=message,
        qr_image=qr_image,
        session_id=session_id
    )


