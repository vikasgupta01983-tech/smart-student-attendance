# ---------------- SUBMIT ATTENDANCE ----------------

@app.route(
    "/submit-attendance/<int:session_id>",
    methods=["POST"]
)
def submit_attendance(session_id):

    roll_number = request.form.get(
        "roll_number", ""
    ).strip()

    password = request.form.get("password", "")

    if not roll_number or not password:

        return (
            "Please enter your roll number and password.",
            400
        )

    connection = get_database_connection()

    try:

        cursor = connection.cursor()

        cursor.execute("""
            SELECT *
            FROM students
            WHERE roll_number = %s
        """, (roll_number,))

        student = cursor.fetchone()

        if student is None:

            return "Student not found. Please register first.", 404

        stored_hash = student["password_hash"]

        if not stored_hash:

            return (
                "No password is set for this student. "
                "Please contact your teacher.",
                400
            )

        if not check_password_hash(stored_hash, password):

            return "Incorrect roll number or password.", 401

        cursor.execute("""
            SELECT id
            FROM sessions
            WHERE id = %s
        """, (session_id,))

        session = cursor.fetchone()

        if session is None:

            return "Attendance session not found.", 404

        attendance_time = datetime.now(
            ZoneInfo("Asia/Kolkata")
        ).strftime("%Y-%m-%d %H:%M:%S")

        cursor.execute("""
            INSERT INTO attendance
            (student_id, session_id, attendance_time)
            VALUES (%s, %s, %s)
        """, (
            student["id"],
            session_id,
            attendance_time
        ))

        connection.commit()

        return render_template("attendance_success.html")

    except IntegrityError:

        connection.rollback()

        return (
            "Attendance has already been marked for this session.",
            409
        )

    finally:

        connection.close()


# ---------------- VIEW ATTENDANCE RECORDS ----------------

@app.route("/attendance-records")
def attendance_records():

    connection = get_database_connection()

    try:

        cursor = connection.cursor()

        # Get all attendance records

        cursor.execute("""
            SELECT
                attendance.id,
                students.name,
                students.roll_number,
                students.class_name,
                sessions.session_name,
                attendance.attendance_time

            FROM attendance

            JOIN students
                ON attendance.student_id = students.id

            JOIN sessions
                ON attendance.session_id = sessions.id

            ORDER BY attendance.id DESC
        """)

        records = cursor.fetchall()

        # Count all sessions

        cursor.execute("""
            SELECT COUNT(*) FROM sessions
        """)

        total_sessions = cursor.fetchone()[0]

        # Calculate each student's attendance

        cursor.execute("""
            SELECT
                students.id,
                students.name,
                students.roll_number,
                students.class_name,

                COUNT(DISTINCT attendance.session_id)
                AS attended_sessions

            FROM students

            LEFT JOIN attendance
                ON students.id = attendance.student_id

            GROUP BY
                students.id,
                students.name,
                students.roll_number,
                students.class_name

            ORDER BY students.roll_number
        """)

        student_attendance = cursor.fetchall()

        attendance_summary = []

        for student in student_attendance:

            attended = student["attended_sessions"]

            if total_sessions > 0:

                percentage = round(
                    (attended / total_sessions) * 100,
                    2
                )

            else:

                percentage = 0

            attendance_summary.append({

                "name": student["name"],

                "roll_number": student["roll_number"],

                "class_name": student["class_name"],

                "attended_sessions": attended,

                "total_sessions": total_sessions,

                "percentage": percentage

            })

    finally:

        connection.close()

    return render_template(
        "attendance_records.html",
        records=records,
        attendance_summary=attendance_summary
    )


